#!/usr/bin/env python3
"""Produce the flecs Bridge-ASM700 builds from the pristine one it vendors.

Two changes, and nothing else. Component columns and a table's entity array are
allocated through `flecs_confine` rather than the OS allocator, so they can be
made to land in one block. And `flecs_table_delete` says which entity it moved
into the hole, because no flecs event does.

    python tools/patch-flecs.py third_party/flecs build/flecs [--omit GROUP]

The script is the record and the applier at once. Every edit is found by its
exact source text inside a named function, and must match the stated number of
times: a flecs that moved a site fails here, by name, rather than compiling
into something half-patched. `--omit allocator` or `--omit hook` leaves one
group out; that exists so the tests can be shown to fail without it.
"""
import argparse
import hashlib
import os
import re
import sys

VERSION = (4, 1, 6)
# the version number does not identify the source: upstream's master carried
# 4.1.6 for months after the tag, with different table storage. the hash does.
SHA256 = {
    'flecs.c': '6005392eb13c0f3c7abdecb2f85271e50934f63919afebf0bbe85f6dfc7320d6',
    'flecs.h': '526036a5a41678e2a43a3cb835e9eaa70fd1993868b1978950c0d275752f69b1',
}

HEADER = '''\
/* Generated by tools/patch-flecs.py. Do not edit, and do not commit. */
#ifndef FLECS_CONFINE_H
#define FLECS_CONFINE_H

#include "flecs.h"

/* Set every member before ecs_init(): flecs allocates through these from its
 * first table on. Sizes are in bytes. `row_moved` may be left NULL. */
typedef struct flecs_confine_t {
    void* (*alloc)(ecs_size_t size);
    void* (*realloc)(void *ptr, ecs_size_t old_size, ecs_size_t new_size);
    void  (*free)(void *ptr, ecs_size_t size);
    /* `entity` now lives at `row` of `table`, and no event will say so. */
    void  (*row_moved)(ecs_world_t *world, ecs_entity_t entity,
                       ecs_table_t *table, int32_t row);
} flecs_confine_t;

extern flecs_confine_t flecs_confine;

#endif
'''

PRELUDE = '''\
#include "flecs_confine.h"
flecs_confine_t flecs_confine;
/* an allocator argument that means "the confined block": a NULL one still
 * means the OS, which the rest of flecs relies on. */
#define FLECS_CONFINE ((ecs_allocator_t*)&flecs_confine)
'''

# (group, function, old text, new text, how many times it must match)
VEC_NULL = r'(ecs_vec_[a-z_]+\()NULL, '
SITES = [
    # where a confined vec gets its memory
    ('allocator', 'flecs_vec_alloc',
     '        if (allocator) {\n            return flecs_alloc_w_dbg_info(',
     '        if (allocator == FLECS_CONFINE) {\n'
     '            return flecs_confine.alloc(size * elem_count);\n'
     '        } else if (allocator) {\n            return flecs_alloc_w_dbg_info(', 1),
    ('allocator', 'flecs_vec_free',
     '    if (allocator) {\n        flecs_free(allocator, elem_size * size, ptr);',
     '    if (allocator == FLECS_CONFINE) {\n'
     '        flecs_confine.free(ptr, elem_size * size);\n'
     '    } else if (allocator) {\n        flecs_free(allocator, elem_size * size, ptr);', 1),
    ('allocator', 'ecs_vec_fini',
     '        if (allocator) {\n            flecs_free(allocator, size * v->size, v->array);',
     '        if (allocator == FLECS_CONFINE) {\n'
     '            flecs_confine.free(v->array, size * v->size);\n'
     '        } else if (allocator) {\n            flecs_free(allocator, size * v->size, v->array);', 1),
    ('allocator', 'ecs_vec_set_size',
     '            if (allocator) {\n#ifdef FLECS_SANITIZE\n',
     '            if (allocator == FLECS_CONFINE) {\n'
     '                v->array = flecs_confine.realloc(\n'
     '                    v->array, size * v->size, size * elem_count);\n'
     '            } else if (allocator) {\n#ifdef FLECS_SANITIZE\n', 1),
    # the calls that pass NULL for a column or an entity array
    ('allocator', 'flecs_bootstrap_component_table', VEC_NULL, None, 4),
    ('allocator', 'flecs_table_fini_data', VEC_NULL, None, 2),
    ('allocator', 'flecs_table_grow_column', VEC_NULL, None, 4),
    ('allocator', 'flecs_table_grow_data', VEC_NULL, None, 1),
    ('allocator', 'flecs_table_fast_append', VEC_NULL, None, 1),
    ('allocator', 'flecs_table_append', VEC_NULL, None, 1),
    ('allocator', 'flecs_table_merge_vec', VEC_NULL, None, 4),
    ('allocator', 'flecs_table_merge_column', VEC_NULL, None, 2),
    ('allocator', 'flecs_table_merge_data', VEC_NULL, None, 4),
    # shrink allocates by hand
    ('allocator', 'flecs_table_shrink',
     'table->data.entities = ecs_os_malloc_n(ecs_entity_t, count);',
     'table->data.entities = flecs_confine.alloc(ECS_SIZEOF(ecs_entity_t) * count);', 1),
    ('allocator', 'flecs_table_shrink',
     '    ecs_os_free(entities);',
     '    if (entities) {\n'
     '        flecs_confine.free(entities, ECS_SIZEOF(ecs_entity_t) * table->data.size);\n'
     '    }', 1),
    ('allocator', 'flecs_table_shrink',
     'columns[i].data = ecs_os_malloc(component_size * count);',
     'columns[i].data = flecs_confine.alloc(component_size * count);', 1),
    ('allocator', 'flecs_table_shrink',
     '        ecs_os_free(data);',
     '        if (data) {\n'
     '            flecs_confine.free(data, component_size * table->data.size);\n'
     '        }', 1),
    # the one row move no event names
    ('hook', 'flecs_table_delete',
     '            record_to_move->row = ECS_ROW_TO_RECORD(row, row_flags);\n',
     '            record_to_move->row = ECS_ROW_TO_RECORD(row, row_flags);\n'
     '            if (flecs_confine.row_moved) {\n'
     '                flecs_confine.row_moved(world, entity_to_move, table, row);\n'
     '            }\n', 1),
]


def die(msg):
    sys.stderr.write('patch-flecs: ' + msg + '\n')
    sys.exit(1)


def body(src, name):
    """(start, end) of the one definition of `name`: its signature line to its closing brace."""
    found = []
    for m in re.finditer(r'^[A-Za-z_][\w \*]*\b%s\($' % re.escape(name), src, re.M):
        close = src.index(')', m.end())
        if src[close + 1:close + 2] == ';':
            continue                                    # a prototype
        end = src.index('\n}\n', close)
        found.append((m.start(), end + 3))
    if len(found) != 1:
        die('expected one definition of %s, found %d' % (name, len(found)))
    return found[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src')
    ap.add_argument('out')
    ap.add_argument('--omit', action='append', default=[], choices=['allocator', 'hook'])
    args = ap.parse_args()

    text = {}
    for f in ('flecs.c', 'flecs.h'):
        raw = open(os.path.join(args.src, f), 'rb').read().replace(b'\r\n', b'\n')
        text[f] = raw.decode('utf-8')

    got = tuple(int(re.search(r'#define FLECS_VERSION_%s\s+(\d+)' % k, text['flecs.h']).group(1))
                for k in ('MAJOR', 'MINOR', 'PATCH'))
    if got != VERSION:
        die('version %d.%d.%d, and this script was written for %d.%d.%d' % (got + VERSION))
    for f in ('flecs.c', 'flecs.h'):
        if hashlib.sha256(text[f].encode('utf-8')).hexdigest() != SHA256[f]:
            die('%s is not the %d.%d.%d this script was written for: its hash differs'
                % ((f,) + VERSION))

    src = text['flecs.c']
    for group, func, old, new, want in SITES:
        if group in args.omit:
            continue
        a, b = body(src, func)
        chunk = src[a:b]
        if new is None:
            chunk, n = re.subn(old, r'\1FLECS_CONFINE, ', chunk)
        else:
            n = chunk.count(old)
            chunk = chunk.replace(old, new)
        if n != want:
            die('%s: expected %d of %r, found %d' % (func, want, old, n))
        src = src[:a] + chunk + src[b:]

    anchor = '#include "flecs.h"\n'
    if src.count(anchor) != 1:
        die('expected one %r' % anchor)
    src = src.replace(anchor, anchor + PRELUDE)

    os.makedirs(args.out, exist_ok=True)
    for f, s in (('flecs.c', src), ('flecs.h', text['flecs.h']), ('flecs_confine.h', HEADER)):
        with open(os.path.join(args.out, f), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(s)


if __name__ == '__main__':
    main()
